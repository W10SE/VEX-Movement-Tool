def FORTALEZA_python_tank_standard(waypoints_m, settings):
    return FORTALEZA_tank_code(waypoints_m, settings, lang="python")


def FORTALEZA_python_tank_smart(waypoints_m, settings):
    return FORTALEZA_tank_code(waypoints_m, settings, lang="python")


def _gen_holonomic_code(waypoints_m, settings, lang="cpp"):
    is_py = (lang == "python")
    pts = convert_units(waypoints_m, settings["units"])
    prefix = "" if is_py else "_"
    motor_default = f"{prefix}motor_" if is_py else "Motor"
    
    motors = {
        "fl": settings.get("motor_fl") or f"{motor_default}fl",
        "fr": settings.get("motor_fr") or f"{motor_default}fr",
        "bl": settings.get("motor_bl") or f"{motor_default}bl",
        "br": settings.get("motor_br") or f"{motor_default}br",
    }
    gear_ratio = settings.get("gear_ratio") or 1.0
    segs = compute_holonomic_wheel_degrees(pts, settings["start_heading"], settings["wheel_dia"], gear_ratio, settings["units"])

    lines = [
        f"# Generated by VEX Path Planner - VEXcode V5 {'Python' if is_py else 'C++'} (Holonomic)",
        "def autonomous():" if is_py else "void autonomous(void) {"
    ]

    for leg_num, leg_vals in enumerate(segs, start=1):
        lines.append(f"    # Leg {leg_num}")
        for (m_key, m_name), deg in zip(motors.items(), leg_vals):
            direction = ("FORWARD" if is_py else "forward") if deg >= 0 else ("REVERSE" if is_py else "reverse")
            if is_py:
                lines.append(f"    {m_name}.spin_for({direction}, {abs(deg):.1f}, DEGREES, wait=False)")
            else:
                lines.append(f"    {m_name}.spinFor({direction}, {abs(deg):.1f}, degrees, false);")

        if is_py:
            conds = " or ".join([f"{m}.is_spinning()" for m in motors.values()])
            lines.extend([f"    while {conds}:", "        wait(10, MSEC)"])
        else:
            conds = " || ".join([f"{m}.isSpinning()" for m in motors.values()])
            lines.append(f"    while ({conds}) {{ wait(10, msec); }}")

    if not is_py:
        lines.append("}")
    return "\n".join(lines)


def genv5pyholonomicstd(waypoints_m, settings):
    return _gen_holonomic_code(waypoints_m, settings, lang="cpp")


def _gen_vexcode_python_holonomic(waypoints_m, settings):
    return _gen_holonomic_code(waypoints_m, settings, lang="python")